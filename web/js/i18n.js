const RTL = new Set(['ar']);

export const LANGS = [
  { code: 'en', label: 'English' },
  { code: 'ar', label: 'العربية' },
];

const STORE_KEY = 'gemp-lang';

export function currentLang() {
  return localStorage.getItem(STORE_KEY) === 'ar' ? 'ar' : 'en';
}

/* Latin digits in Arabic, deliberately.
 *
 * `ar-EG` on its own formats numbers in Arabic-Indic digits (٠١٢٣). Egyptian
 * government and engineering documents overwhelmingly set figures in Latin
 * digits, and this product's numbers are meant to be read against a printed bill
 * of quantities and a cost catalogue that use them. `-u-nu-latn` keeps Arabic
 * grouping and decimal conventions while leaving the digits legible to everyone
 * in the room. */
export function locale() {
  return currentLang() === 'ar' ? 'ar-EG-u-nu-latn' : 'en-US';
}

function applyDocument(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr';
}

export function setLangCode(code) {
  const next = code === 'ar' ? 'ar' : 'en';
  localStorage.setItem(STORE_KEY, next);
  applyDocument(next);
  window.dispatchEvent(new CustomEvent('gemp:lang', { detail: { lang: next } }));
}

/* Applied once at boot, before first paint of any view, so direction is never
 * wrong-then-fixed: a flash of left-to-right before flipping is exactly the
 * kind of sloppiness that says "bolted on". */
applyDocument(currentLang());

const has = (table, key) =>
  Boolean(table) && Object.prototype.hasOwnProperty.call(table, key);

export function t(key, vars) {
  const table = STRINGS[currentLang()];
  /* An untranslated string reads as English, not as `overview.budget`. A gap in
   * the Arabic table is a missing translation; showing the key turns it into a
   * visible defect. */
  let out = has(table, key) ? table[key]
    : has(STRINGS.en, key) ? STRINGS.en[key]
    : key;

  /* `{name}` placeholders, so a sentence with a number in the middle of it can be
   * translated as a sentence. Arabic word order is not English word order, and a
   * string built by concatenating fragments around a value can only ever come out
   * in the order the English was written in. */
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, (whole, name) =>
      (Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole));
  }
  return out;
}

/* True when the interface is running right to left. Used where a value has to be
   placed rather than merely styled - a chart's axis side, an SVG label anchor -
   because CSS logical properties do not reach inside a drawn figure. */
export function isRtl() {
  return RTL.has(currentLang());
}
