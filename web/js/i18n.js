/* Arabic and right-to-left, across every screen.
 *
 * This began as the demonstration path only - shell, navigation, Overview, map -
 * on the argument that a consistently English screen reads as scope while a
 * half-translated one reads as a bug. That argument was sound and the scope was
 * still wrong: a reader who switches to Arabic and finds five of nine screens in
 * English has not been given the feature, they have been shown where it stops.
 *
 * The Arabic is written, not transliterated. Where a literal rendering would be
 * meaningless or misleading in Arabic the phrasing follows Egyptian public-sector
 * usage instead - `Allocation` is تخصيص (budget allocation, the administrative
 * act) rather than توزيع (physical distribution); `Evidence` is الأدلة in the
 * sense a report carries evidence, not إثبات; `Alert inbox` is صندوق التنبيهات
 * rather than a calque of `inbox`; a `run` of the optimizer is تشغيل, not جري.
 *
 * `t()` falls back to the English string, and to the key itself if even that is
 * missing, so a forgotten key can never blank a control. That fallback only
 * works because `en` is a real table below - an empty one renders raw keys. Direction and
 * language live on <html>, which is what flips the stylesheet's logical
 * properties; views re-render on the gemp:lang event so open screens follow.
 */

